using System.Diagnostics.CodeAnalysis;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;
using Microsoft.Extensions.Logging;

namespace ScrubJay.Enhancements.BuildTasks;

public sealed class GenerateGuardPartsBuildTask : Microsoft.Build.Utilities.Task
{
    private readonly ILogger<GenerateGuardPartsBuildTask> _logger;

    [Required]
    public required ITaskItem[] ValidateParts { get; set; } = [];

    [Output]
    public ITaskItem[] GuardParts { get; set; } = [];


    public GenerateGuardPartsBuildTask()
    {
        _logger = new TaskLoggingHelperLogger<GenerateGuardPartsBuildTask>(this.Log);
    }

    private string? GetFullPath(ITaskItem validatePart)
    {
        string? validateFullPath = validatePart.GetMetadata("FullPath");
        if (string.IsNullOrEmpty(validateFullPath))
        {
            _logger.LogError("ValidatePart '{ValidatePart}' does not have valid FullPath Metadata", validatePart);
            return null;
        }

        if (!File.Exists(validateFullPath))
        {
            _logger.LogError("ValidatePart '{ValidatePart}'s FullPath '{FullPath}' does not exist", validatePart, validateFullPath);
            return null;
        }

        return validateFullPath;
    }
    
    private ITaskItem? GenerateGuardPart(string validatePath)
    {
        var directory = Path.GetDirectoryName(validatePath)!;
        var fileName = Path.GetFileName(validatePath)
            .Replace("Validate", "Guard")
            .Replace(".cs", ".g.cs");
        var guardPath = Path.Combine(directory, fileName);
        
        _logger.LogInformation("Converting '{ValidatePath}' to '{GuardPath}'", validatePath, guardPath);
        
        try
        {
            using FileStream validateFileStream = File.Open(validatePath, FileMode.Open, FileAccess.Read, FileShare.Read);
            using TextReader validateReader = new StreamReader(validateFileStream, Encoding.UTF8);

            using FileStream guardFileStream = File.Open(guardPath, FileMode.Create, FileAccess.Write, FileShare.None);
            using TextWriter guardWriter = new StreamWriter(guardFileStream, Encoding.UTF8);

            guardWriter.WriteLine("/// <auto-generated/>");
            guardWriter.WriteLine("#nullable enable");

            string? line;
            while ((line = validateReader.ReadLine()) is not null)
            {
                line = line
                    .Replace("Validate", "Guard");

                // fix (Ref)Result<T> return to T
                var resultReturnMatch = Regex.Match(line, @"public\s+static\s+((?:Ref|)Result<([\w\d_]+)>)\s+\w+",
                    RegexOptions.Compiled);
                if (resultReturnMatch.Success && resultReturnMatch.Groups.Count == 3)
                {
                    line = line.Replace(
                        resultReturnMatch.Groups[1].Value,
                        resultReturnMatch.Groups[2].Value);
                }

                // fix return exception -> throw exception
                var returnExMatch = Regex.Match(line, @"(return Ex\.|return new [\w]*Exception).+", RegexOptions.Compiled);
                if (returnExMatch.Success && returnExMatch.Groups.Count == 2)
                {
                    var part = returnExMatch.Groups[1].Value;
                    line = line.Replace(part, $"throw{part[6..]}");
                }

                guardWriter.WriteLine(line);
            }
            
            guardWriter.Flush();
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Could not generate Guard Part for '{ValidatePath}'", validatePath);
            return null;
        }

        return new TaskItem(guardPath, true);
    }

    public override bool Execute()
    {
        _logger.LogInformation("Validate->Guard BuildTask Starting...");

        List<string> validatePaths = ValidateParts
            .Select(part => GetFullPath(part))
            .Where(path => !string.IsNullOrEmpty(path))
            .ToList()!;
        
        // we want to clear out all unique parent directories of previously generated files
        HashSet<string> uniqueDirs = validatePaths
            .Select(path => Path.GetDirectoryName(path))
            .Where(path => !string.IsNullOrEmpty(path))
            .ToHashSet()!;

        foreach (var dir in uniqueDirs)
        {
            _logger.LogInformation("Clearing out previously generated files in '{Directory}'", dir);

            var directory = new DirectoryInfo(dir);
            var generatedFiles = directory.GetFiles("*.g.cs", SearchOption.TopDirectoryOnly);
            foreach (var file in generatedFiles)
            {
                file.Delete();
                _logger.LogInformation("Deleted '{File}'", file.FullName);
            }
        }

        var guardParts = new List<ITaskItem>();
        
        foreach (var validatePath in validatePaths)
        {
            var guardPart = GenerateGuardPart(validatePath);
            if (guardPart is not null)
            {
                guardParts.Add(guardPart);
            }
        }
        
        _logger.LogInformation("Validate->Guard BuildTask Finished");

        this.GuardParts = guardParts.ToArray();
        
        return !Log.HasLoggedErrors;
    }
}